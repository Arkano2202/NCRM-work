function availableLanguages(): array
{
    return [
        'ES' => 'Español',
        'EN' => 'English',
        'IT' => 'Italiano',
    ];
}

function normalizeLanguageCode(?string $language): string
{
    $language = strtoupper(trim((string) $language));
    return array_key_exists($language, availableLanguages()) ? $language : 'ES';
}

function appLanguage(): string
{
    return normalizeLanguageCode($_SESSION['idioma'] ?? 'ES');
}

